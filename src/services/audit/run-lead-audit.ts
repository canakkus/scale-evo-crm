import { prisma } from "@/lib/prisma";
import { createSupabaseAdminClient } from "@/lib/supabase/admin";
import { runScrapling } from "@/services/scrapling";
import { computeSeverityScore, runSecurityAudit, type AuditIssueDraft } from "./security-audit";

const BUCKET = "lead-attachments";
/** Mindestabstand zwischen zwei Audits (schont System-Chrome und fremde Server). */
const QUEUE_COOLDOWN_MS = 3_000;
/** Manuelles Neu-Auditieren eines Leads erst nach dieser Zeit. */
export const AUDIT_RERUN_COOLDOWN_MS = 10 * 60_000;

let queueTail: Promise<unknown> = Promise.resolve();

/**
 * Serialisiert alle Audits (Concurrency 1) mit Cooldown dazwischen.
 * Reicht fuer Einzelanlage und Sammel-Import; bewusst kein externer Queue-Worker.
 */
export function enqueueLeadAudit(leadId: string): Promise<void> {
  const job = queueTail.then(async () => {
    try {
      await runLeadAudit(leadId);
    } catch (err) {
      console.error("[audit] unerwarteter Fehler", leadId, err);
      await prisma.lead
        .update({ where: { id: leadId }, data: { auditStatus: "failed" } })
        .catch(() => undefined);
    }
    await new Promise((resolve) => setTimeout(resolve, QUEUE_COOLDOWN_MS));
  });
  queueTail = job;
  return job;
}

function storagePathFromPublicUrl(url: string): string | null {
  const marker = `/${BUCKET}/`;
  const idx = url.indexOf(marker);
  return idx === -1 ? null : decodeURIComponent(url.slice(idx + marker.length));
}

async function removeOldAutoScreenshots(leadId: string) {
  const old = await prisma.leadAttachment.findMany({ where: { leadId, isAutoGenerated: true } });
  if (old.length === 0) return;
  const paths = old.map((a) => storagePathFromPublicUrl(a.url)).filter((p): p is string => Boolean(p));
  if (paths.length > 0) {
    await createSupabaseAdminClient().storage.from(BUCKET).remove(paths).catch(() => undefined);
  }
  await prisma.leadAttachment.deleteMany({ where: { leadId, isAutoGenerated: true } });
}

async function takeAndStoreScreenshot(
  leadId: string,
  url: string,
): Promise<{ issues: AuditIssueDraft[]; stored: boolean }> {
  const extra: AuditIssueDraft[] = [];
  try {
    const shot = (await runScrapling("screenshot", { url })) as {
      image_base64?: string;
      console_errors?: string[];
      failed_requests?: string[];
      error?: string;
    };
    if (shot.error || !shot.image_base64) {
      console.warn("[audit] Screenshot fehlgeschlagen:", shot.error);
      return { issues: extra, stored: false };
    }

    if (shot.console_errors && shot.console_errors.length > 0) {
      extra.push({
        category: "BROKEN",
        severity: "MEDIUM",
        code: "console-errors",
        title: `${shot.console_errors.length} JavaScript-/Console-Fehler beim Laden`,
        description: "Die Seite wirft beim Aufruf Fehler im Browser - Funktionen koennen kaputt sein.",
        snippet: shot.console_errors.join("\n"),
      });
    }
    if (shot.failed_requests && shot.failed_requests.length > 0) {
      extra.push({
        category: "BROKEN",
        severity: "LOW",
        code: "failed-requests",
        title: `${shot.failed_requests.length} Ressourcen laden nicht (HTTP 4xx/5xx)`,
        description: "Bilder, Skripte oder Styles fehlen - Hinweis auf kaputte oder verwaiste Inhalte.",
        snippet: shot.failed_requests.join("\n"),
      });
    }

    const buffer = Buffer.from(shot.image_base64, "base64");
    const storagePath = `leads/${leadId}/audit-${Date.now()}.png`;
    const supabase = createSupabaseAdminClient();
    const { error: uploadError } = await supabase.storage
      .from(BUCKET)
      .upload(storagePath, buffer, { contentType: "image/png", upsert: false });
    if (uploadError) {
      console.error("[audit] Upload-Fehler", uploadError.message);
      return { issues: extra, stored: false };
    }
    const { data } = supabase.storage.from(BUCKET).getPublicUrl(storagePath);

    await removeOldAutoScreenshots(leadId);
    await prisma.leadAttachment.create({
      data: {
        leadId,
        url: data.publicUrl,
        fileName: "Auto-Scan Screenshot",
        fileSize: buffer.length,
        mimeType: "image/png",
        isAutoGenerated: true,
      },
    });
    return { issues: extra, stored: true };
  } catch (err) {
    // Kein Browser verfuegbar (z. B. Vercel): Audit bleibt gueltig, nur ohne Screenshot.
    console.warn("[audit] Screenshot nicht verfuegbar:", err instanceof Error ? err.message : err);
    return { issues: extra, stored: false };
  }
}

export async function runLeadAudit(leadId: string): Promise<void> {
  const lead = await prisma.lead.findUnique({
    where: { id: leadId },
    select: { id: true, website: true },
  });
  if (!lead) return;

  if (!lead.website?.trim()) {
    await prisma.lead.update({ where: { id: leadId }, data: { auditStatus: "skipped" } });
    return;
  }

  await prisma.lead.update({
    where: { id: leadId },
    data: { auditStatus: "running", auditAttemptedAt: new Date() },
  });

  const result = await runSecurityAudit(lead.website);
  const issues = [...result.issues];

  if (result.shouldScreenshot) {
    const shot = await takeAndStoreScreenshot(leadId, result.url);
    for (const issue of shot.issues) {
      if (!issues.some((existing) => existing.code === issue.code)) issues.push(issue);
    }
  }

  await prisma.$transaction([
    prisma.leadAuditIssue.deleteMany({ where: { leadId } }),
    prisma.leadAuditIssue.createMany({ data: issues.map((issue) => ({ ...issue, leadId })) }),
    prisma.lead.update({
      where: { id: leadId },
      data: { auditStatus: "done", auditSeverity: computeSeverityScore(issues) },
    }),
  ]);
}
